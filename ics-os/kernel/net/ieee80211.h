#ifndef ICSOS_NET_IEEE80211_H
#define ICSOS_NET_IEEE80211_H

/*
  Minimal 802.11 constants for ICS-OS Wi-Fi framework.
  Not a full mac80211 port.
*/

#define WIFI_ADDR_LEN 6
#define ETH_ALEN WIFI_ADDR_LEN

#define IEEE80211_FTYPE_MGMT 0x0000
#define IEEE80211_FTYPE_CTL  0x0004
#define IEEE80211_FTYPE_DATA 0x0008

#define IEEE80211_STYPE_ASSOC_REQ    0x0000
#define IEEE80211_STYPE_ASSOC_RESP   0x0010
#define IEEE80211_STYPE_REASSOC_REQ  0x0020
#define IEEE80211_STYPE_REASSOC_RESP 0x0030
#define IEEE80211_STYPE_PROBE_REQ    0x0040
#define IEEE80211_STYPE_PROBE_RESP   0x0050
#define IEEE80211_STYPE_BEACON       0x0080
#define IEEE80211_STYPE_AUTH         0x00B0
#define IEEE80211_STYPE_DEAUTH       0x00C0

enum wifi_state {
    WIFI_STATE_DOWN = 0,
    WIFI_STATE_INIT,
    WIFI_STATE_SCANNING,
    WIFI_STATE_AUTHENTICATING,
    WIFI_STATE_ASSOCIATING,
    WIFI_STATE_CONNECTED,
    WIFI_STATE_ERROR
};

#endif

/*
  Host TAP for USB CDC-ACM configuration parsing.
  Covers QEMU usb-serial, a Pico-style IAD composite, MSC rejection,
  missing data interface, truncated descriptors, and bulk-only checks.
*/
#include <stdio.h>
#include <string.h>

#include "kernel/hardware/usb/usb_cdc_acm.h"

static int check(const char *name, int condition)
{
    if (!condition) {
        printf("not ok - %s\n", name);
        return 0;
    }
    printf("ok - %s\n", name);
    return 1;
}

/* QEMU usb-serial: ACM comm IF0 (interrupt EP) + data IF1 (bulk 2/3). */
static const unsigned char qemu_acm[] = {
    0x09, 0x02, 0x43, 0x00, 0x02, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x01, 0x02, 0x02, 0x01, 0x00,
    0x05, 0x24, 0x00, 0x10, 0x01,
    0x05, 0x24, 0x01, 0x00, 0x01,
    0x04, 0x24, 0x02, 0x02,
    0x05, 0x24, 0x06, 0x00, 0x01,
    0x07, 0x05, 0x81, 0x03, 0x08, 0x00, 0x09,
    0x09, 0x04, 0x01, 0x00, 0x02, 0x0A, 0x00, 0x00, 0x00,
    0x07, 0x05, 0x02, 0x02, 0x40, 0x00, 0x00,
    0x07, 0x05, 0x83, 0x02, 0x40, 0x00, 0x00
};

/* Pico/RP2 gadget: IAD + ACM + data, HS-sized bulk packets. */
static const unsigned char pico_iad[] = {
    0x09, 0x02, 0x4B, 0x00, 0x02, 0x01, 0x00, 0x80, 0x32,
    0x08, 0x0B, 0x00, 0x02, 0x02, 0x02, 0x01, 0x00,
    0x09, 0x04, 0x00, 0x00, 0x01, 0x02, 0x02, 0x01, 0x00,
    0x05, 0x24, 0x00, 0x10, 0x01,
    0x05, 0x24, 0x01, 0x00, 0x01,
    0x04, 0x24, 0x02, 0x02,
    0x05, 0x24, 0x06, 0x00, 0x01,
    0x07, 0x05, 0x81, 0x03, 0x10, 0x00, 0x09,
    0x09, 0x04, 0x01, 0x00, 0x02, 0x0A, 0x00, 0x00, 0x00,
    0x07, 0x05, 0x02, 0x02, 0x00, 0x02, 0x00,
    0x07, 0x05, 0x83, 0x02, 0x00, 0x02, 0x00
};

static const unsigned char msc_only[] = {
    0x09, 0x02, 0x20, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x02, 0x08, 0x06, 0x50, 0x00,
    0x07, 0x05, 0x81, 0x02, 0x40, 0x00, 0x00,
    0x07, 0x05, 0x02, 0x02, 0x40, 0x00, 0x00
};

static const unsigned char acm_no_data[] = {
    0x09, 0x02, 0x1C, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x01, 0x02, 0x02, 0x01, 0x00,
    0x07, 0x05, 0x81, 0x03, 0x08, 0x00, 0x09
};

static const unsigned char data_in_only[] = {
    0x09, 0x02, 0x20, 0x00, 0x02, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x00, 0x02, 0x02, 0x01, 0x00,
    0x09, 0x04, 0x01, 0x00, 0x01, 0x0A, 0x00, 0x00, 0x00,
    0x07, 0x05, 0x83, 0x02, 0x40, 0x00, 0x00
};

static const unsigned char hid_interrupt[] = {
    0x09, 0x02, 0x19, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x01, 0x03, 0x01, 0x01, 0x00,
    0x07, 0x05, 0x81, 0x03, 0x08, 0x00, 0x0A
};

/* QEMU usb-serial: FTDI vendor class 0xFF, bulk 1/2. */
static const unsigned char qemu_ftdi[] = {
    0x09, 0x02, 0x20, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x02, 0xFF, 0xFF, 0xFF, 0x00,
    0x07, 0x05, 0x81, 0x02, 0x40, 0x00, 0x00,
    0x07, 0x05, 0x02, 0x02, 0x40, 0x00, 0x00
};

static const unsigned char overflow[] = {
    0x09, 0x02, 0x0B, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
    0x09, 0x04, 0x00, 0x00, 0x00, 0x02, 0x02, 0x01, 0x00
};

int main(void)
{
    usb_cdc_acm_info info;
    int ok = 1;

    printf("TAP version 13\n1..16\n");

    memset(&info, 0, sizeof info);
    ok &= check("QEMU usb-serial ACM parses",
                usb_parse_cdc_acm(qemu_acm, sizeof qemu_acm, &info) == 1);
    ok &= check("QEMU ACM uses bulk out=2 in=3 mps=64 cfg=1",
                info.ep_out == 2 && info.ep_in == 3 &&
                info.mps_out == 64 && info.mps_in == 64 &&
                info.cfgval == 1 && info.comm_if == 0 &&
                info.data_if == 1);

    memset(&info, 0, sizeof info);
    ok &= check("Pico IAD ACM parses",
                usb_parse_cdc_acm(pico_iad, sizeof pico_iad, &info) == 1);
    ok &= check("Pico IAD bulk mps=512",
                info.ep_out == 2 && info.ep_in == 3 &&
                info.mps_out == 512 && info.mps_in == 512);

    ok &= check("MSC-only config is not ACM",
                usb_parse_cdc_acm(msc_only, sizeof msc_only, &info) == 0);
    ok &= check("MSC-only is not vendor serial either",
                usb_parse_vendor_bulk_serial(msc_only, sizeof msc_only,
                                             &info) == 0);
    ok &= check("ACM without data IF is rejected",
                usb_parse_cdc_acm(acm_no_data, sizeof acm_no_data, &info) == 0);
    ok &= check("data IF with only IN is rejected",
                usb_parse_cdc_acm(data_in_only, sizeof data_in_only,
                                  &info) == 0);
    ok &= check("HID interrupt-only is rejected",
                usb_parse_cdc_acm(hid_interrupt, sizeof hid_interrupt,
                                  &info) == 0);
    ok &= check("truncated config header is rejected",
                usb_parse_cdc_acm(qemu_acm, 8, &info) == 0);
    ok &= check("descriptor that overruns total is rejected",
                usb_parse_cdc_acm(overflow, 11, &info) == 0);
    ok &= check("NULL buffer is rejected",
                usb_parse_cdc_acm(0, sizeof qemu_acm, &info) == 0);
    ok &= check("NULL out info is rejected",
                usb_parse_cdc_acm(qemu_acm, sizeof qemu_acm, 0) == 0);

    memset(&info, 0, sizeof info);
    ok &= check("QEMU FTDI vendor serial parses",
                usb_parse_vendor_bulk_serial(qemu_ftdi, sizeof qemu_ftdi,
                                             &info) == 1);
    ok &= check("QEMU FTDI bulk out=2 in=1",
                info.ep_out == 2 && info.ep_in == 1 && info.cfgval == 1);
    ok &= check("console parser accepts FTDI after ACM miss",
                usb_parse_usb_console(qemu_ftdi, sizeof qemu_ftdi,
                                      &info) == 1);

    return ok ? 0 : 1;
}
